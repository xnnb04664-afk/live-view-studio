let activeLanguage: AppLanguage = "zh-CN";

export function readAppLanguage(): AppLanguage {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en-US" ? "en-US" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

export function setAppLanguage(language: AppLanguage): void {
  activeLanguage = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Keep the selected language for this session if storage is unavailable.
  }
}

export function t(value: string): string {
  if (activeLanguage !== "en-US") return value;
  let result = value;
  for (const [source, translated] of Object.entries(english).sort((a, b) => b[0].length - a[0].length)) {
    if (result.includes(source)) result = result.split(source).join(translated);
  }
  return result;
}
